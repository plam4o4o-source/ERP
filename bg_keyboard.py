"""Одит (находка С4, среден риск): нормализация на текст, погрешно въведен
с включена кирилска подредба на клавиатурата (БДС), вместо латиница —
сървърна част от поправката (вижте static/app.js за клиентската част:
initGlobalScan вече ползва e.code вместо e.key за глобалния буфер, което е
НЕЗАВИСИМО от активната подредба; тук е ВТОРА линия защита за случаите,
когато потребителят реално е написал/сканирал в един от видимите текстови
полета за сканиране (#scan-input/#sidebar-scan-input) — там символите
стигат до Flask вече готови от браузъра/ОС, СЛЕД превода през подредбата,
затова e.code не помага изобщо там (виж routes_dashboard.scan()).

Пример: физически скенер, конфигуриран да „пише“ CMR-07082026-0001 (Code128
съдържа само латиница/цифри), при активна кирилска подредба на Windows
вкарва в полето съвсем различни, кирилски символи — документът остава
ненамираем и без никакво обяснение защо.

Таблицата по-долу е ИЗВЕДЕНА от официалния стандарт „БДС 5237:2006“ (същия,
към който препраща одитът — „нормализация по БДС картата“), чрез реалната
X11/XKB дефиниция на подредбата (пакет xkb-data, файл
/usr/share/X11/xkb/symbols/bg, вариант "bds" — „the BDS keyboard layout
compliant with the proposed Bulgarian state standard BDS 5237:2006“), а НЕ
измислена/предположена — всеки ред по-долу отговаря на точно една физическа
клавишна позиция от тази дефиниция.

ВАЖНА ЗАБЕЛЕЖКА за обхвата: Windows исторически предлага подредба, наречена
просто „Bulgarian“ (не „Bulgarian (Phonetic)“), която е близка, но НЕ
непременно byte-for-byte идентична с официалния стандарт БДС 5237:2006 за
всяка отделна буква (по-старият вграден в Windows драйвер предхожда
стандарта от 2006 и не е потвърдено дали Microsoft го е обновили изцяло).
Затова тази нормализация се прилага в routes_dashboard.scan() САМО като
резервен ВТОРИ опит за търсене, ако прекият (буквален) опит не намери
документ — грешна/непокрита буква тук просто означава, че резервният опит
ОСТАВА без резултат (същото поведение като преди поправката: съобщение
„няма документ“), НИКОГА не пренасочва към ПОГРЕШЕН документ (低 риск от
своя страна — виж routes_dashboard.scan() и regression тестовете в
tests/test_audit_2026_08.py за пълната аргументация)."""

#: Обратна таблица: кирилски символ (какъвто РЕАЛНО се появява в полето при
#: кирилска подредба) -> латинският/символен знак, който физическият клавиш
#: означава при латинска (US QWERTY) подредба — точно каквото e Code128
#: скенерът в действителност изпраща. Извлечена ред по ред от блока
#: xkb_symbols "bds" (виж bg(bds) в /usr/share/X11/xkb/symbols/bg):
#: горен ред (Q..P), среден ред (A..L), долен ред (Z..M) плюс клавиша "/"
#: (физически същата позиция като на латинска подредба, но дава "б"/"Б"
#: тук). Цифрите и тирето НЕ са включени нарочно — на тази подредба те са
#: НЕПРОМЕНЕНИ спрямо латиница на ниво без Shift (вижте коментара в
#: тестовете), затова не се нуждаят от превод.
_REVERSE_MAP = {
    # горен ред: Q W E R T Y U I O P
    "ы": "Q",
    "у": "W", "У": "W",
    "е": "E", "Е": "E",
    "и": "R", "И": "R",
    "ш": "T", "Ш": "T",
    "щ": "Y", "Щ": "Y",
    "к": "U", "К": "U",
    "с": "I", "С": "I",
    "д": "O", "Д": "O",
    "з": "P", "З": "P",
    # среден ред: A S D F G H J K L
    "ь": "A", "ѝ": "A",  # ѝ — вижте docstring-а по-горе (Shift+A на тази подредба)
    "я": "S", "Я": "S",
    "а": "D", "А": "D",
    "о": "F", "О": "F",
    "ж": "G", "Ж": "G",
    "г": "H", "Г": "H",
    "т": "J", "Т": "J",
    "н": "K", "Н": "K",
    "в": "L", "В": "L",
    # долен ред: Z X C V B N M , .
    "ю": "Z", "Ю": "Z",
    "й": "X", "Й": "X",
    "ъ": "C", "Ъ": "C",
    "э": "V", "Э": "V",
    "ф": "B", "Ф": "B",
    "х": "N", "Х": "N",
    "п": "M", "П": "M",
    "р": ",",
    "л": ".",
    # "/" клавишът (номерата на документи често го съдържат, напр.
    # "0001/2026") дава "б"/"Б" на тази подредба.
    "б": "/", "Б": "/",
}


def normalize_bds_cyrillic(text):
    """Превежда всеки символ на `text`, който е сгрешено кирилско „ехо“ на
    латинска клавиша (по БДС картата по-горе), обратно към latinския/
    символния знак — знаци, липсващи в таблицата (цифри, тире, вече
    правилна латиница, интервал...), остават НЕПРОМЕНЕНИ. Празен вход ->
    празен резултат (никога не хвърля грешка — вижте routes_dashboard.scan(),
    ползва се само като резервен опит за търсене)."""
    if not text:
        return text
    return "".join(_REVERSE_MAP.get(ch, ch) for ch in text)
