# -*- coding: utf-8 -*-
"""Помощни функции за безопасно вграждане на JSON в HTML/JS.

Изнесено в отделен модул (вместо да живее направо в app.py), за да може
да се тества без да се внася тежкият app.py (който инициализира Flask и
базата данни при самия импорт — виж tests/README.md).
"""
import json

# Заменяме символите, които могат да прекъснат преждевременно <script> блок
# или да объркат HTML парсъра, с еквивалентните им \uXXXX escape поредици.
# Вътре в JS низов литерал (какъвто е всеки низ в JSON извода) < и
# останалите се интерпретират от JS engine-а точно като оригиналния символ
# — резултатът е СЪЩИЯТ обект по време на изпълнение, но HTML парсърът вече
# не вижда буквалната последователност "</script>", "<script>" или "&...;"
# в изходния код на страницата. Същият подход ползва вградения филтър
# `tojson` на Flask/Jinja за точно този сценарий (вграждане на JSON в JS).
_DANGEROUS = {
    "<": "\\u003c",
    ">": "\\u003e",
    "&": "\\u0026",
    "'": "\\u0027",
}


def dumps_for_inline_script(data):
    """json.dumps(data), безопасен за директно вграждане в <script> блок.

    Пример: `window.CLIENTS = {{ some_json_string|safe }};` — ако
    some_json_string дойде от `json.dumps(...)` без тази функция и данните
    съдържат потребителски низ като `"</script><script>alert(1)</script>"`
    (напр. име на клиент), той СЧУПВА текущия <script> блок и изпълнява
    произволен JS за всеки потребител, отворил формата (stored XSS).
    """
    raw = json.dumps(data, ensure_ascii=False)
    for ch, esc in _DANGEROUS.items():
        raw = raw.replace(ch, esc)
    return raw
