# -*- coding: utf-8 -*-
"""Начална конфигурация на ПачоЛогистик (bootstrap).

Съдържа само настройки, нужни ПРЕДИ да може да се отвори базата данни —
основно къде физически да стои файлът ѝ (локално или на мрежов диск).
Всички останали настройки (тема, архивиране и т.н.) се пазят в самата база.
"""
import json
import os
import sys
import tempfile
import threading
import time

import applog

# Одит (25.08.2026, находка №1, висока): целият достъп до pacho_config.json —
# И записът, И четенето — се сериализира с този катинар. Без него — при мрежов
# режим, където няколко служителя + админ пишат/четат конфигурацията почти
# едновременно — два конкурентни save_config се блъскаха в един и същ споделен
# .tmp файл, os.replace на втория гърмеше с FileNotFoundError (гол 500 за
# админа), конкурентен четец прочиташе повреден/празен файл и падаше към
# DEFAULTS (db_path="" → нова празна база — точно катастрофата, която №24
# трябваше да предотврати), а в най-лошия случай крайното състояние оставаше
# ЗАГУБЕНО. Проверено с изпълнение: 2×300 записа + 2×600 четения → 208
# FileNotFoundError, 1169 повредени четения, накрая db_path/токен празни.
#
# Одит (26.08.2026, находка №1-Б, ВИСОКА — доуточнение след Windows CI):
# първата версия на поправката сериализираше само ПИСАЧИТЕ, а четците четяха
# файла извън катинара. На POSIX това е безобидно: rename() върху файл, който
# някой държи отворен, минава спокойно. На WINDOWS — реалната платформа на
# програмата — НЕ минава: `os.replace` гърми с `PermissionError [WinError 5]
# Access is denied`, защото Python отваря файла БЕЗ FILE_SHARE_DELETE, значи
# всеки отворен четец блокира преименуването. Тоест на Windows поправката
# оставаше НЕПЪЛНА и админ, който пази системна настройка точно докато
# waitress нишка чете конфигурацията, пак получаваше гол срив — само че по
# друг механизъм. Доловено от собствения ни регресионен тест на истински
# windows-latest runner (v3.66.1 Build and Release, run #87), не от код-ревю:
# на Linux този клас грешка е физически невъзможно да се възпроизведе.
#
# Бележка (25.08.2026): най-честият конкурентен четец беше backup.mark_dirty
# (викаше load_config при ВСЕКИ запис на документ за автоматичната GitHub
# синхронизация). Тази синхронизация е премахната, значи честотата на
# едновременните четци рязко падна — но катинарът остава напълно уместен:
# системните настройки (мрежа/път до базата) все още се четат и пишат, а на
# Windows дори един-единствен паралелен четец е достатъчен за срива по-горе.
# RLock (не Lock), защото save_config вика load_config, докато вече го държи.
_config_lock = threading.RLock()

#: Одит (26.08.2026, находка №1-Б): колко пъти да опитаме `os.replace`, ако
#: Windows върне „Access is denied“. Вътрешнопроцесните четци вече са под
#: катинара по-горе, но файлът може да е отворен и от ДРУГ процес, който
#: катинарът няма как да достигне: втори компютър, четящ конфигурацията от
#: същия мрежов дял, антивирусна програма или Windows Search индексатор,
#: докоснал файла точно в този момент. Всичките държат файла милисекунди,
#: затова кратък retour е достатъчен; след изчерпването им грешката излиза
#: нормално (старата конфигурация остава непокътната).
_REPLACE_RETRIES = 10
_REPLACE_RETRY_SLEEP = 0.05

if getattr(sys, "frozen", False):
    _BASE_DIR = os.path.dirname(os.path.abspath(sys.executable))
else:
    _BASE_DIR = os.path.dirname(os.path.abspath(__file__))

CONFIG_PATH = os.path.join(_BASE_DIR, "pacho_config.json")

DEFAULTS = {
    # Ако е зададен, базата данни се отваря от този път (напр. мрежов диск:
    # \\SERVER\share\pacho_logistic.db или Z:\ПачоЛогистик\pacho_logistic.db).
    # Празно = по подразбиране, до .exe/скрипта.
    "db_path": "",
    # Мрежов режим: слуша на 0.0.0.0, за да може да се отваря от други
    # компютри в локалната мрежа през браузър (http://IP-на-сървъра:5000).
    "network_mode": False,
    "network_port": 5000,
}
# Бележка (25.08.2026): автоматичната синхронизация с GitHub беше премахната
# по заявка на потребителя — заедно с нея и настройките gh_owner/gh_repo/
# gh_branch/gh_path/gh_token/gh_auto_sync, които стояха тук. Стари
# pacho_config.json файлове може още да ги съдържат — те просто се игнорират
# (нищо вече не ги чете). Резервното копиране остана само локално (папка/
# мрежов диск, настройки в самата база), а автоматичното ОБНОВЯВАНЕ на
# програмата от GitHub (updater.py) е отделна, незасегната функция.


# Одит (19.08.2026, находка №30, средна): ключовете, които ОСТАНАЛИЯТ код
# третира безусловно като текст (`.strip()`, `.startswith()`, конкатенация
# в URL). Списъкът се строи от самите DEFAULTS, за да не може ново текстово
# поле да бъде добавено там и забравено тук.
_TEXT_KEYS = tuple(k for k, v in DEFAULTS.items() if isinstance(v, str))


def _coerce_text_setting(key, value, default):
    """Одит (19.08.2026, находка №30, средна): ръчната редакция на
    pacho_config.json е ДОКУМЕНТИРАНИЯТ bootstrap за мрежови инсталации —
    човек с текстов редактор лесно пише `"db_path": 12345` (без кавички)
    или подава списък. Поправката на находка №45 покри само `network_port`;
    всички ОСТАНАЛИ текстови полета продължаваха да гърмят необработено ПРИ
    САМИЯ ИМПОРТ на db.py (`config.resolve_db_path` → `AttributeError: 'int'
    object has no attribute 'strip'`). В компилираната .exe версия
    (--windowed) това е ТИХА смърт: програмата просто не се отваря, без
    прозорец и без съобщение.

    Толерантно привеждане вместо срив, по същия модел като
    `get_network_port` по-долу: число се ползва като текст (най-вероятно е
    просто забравена кавичка), а стойност без смислен текстов еквивалент
    (списък/речник/булево) пада към подразбиращата се — и в двата случая с
    предупреждение в лога, за да има следа какво е било пренебрегнато."""
    if isinstance(value, str):
        return value
    if value is None:
        return default
    if not isinstance(value, bool) and isinstance(value, (int, float)):
        applog.log_warning(
            "config.load_config",
            "стойността на %s в pacho_config.json е число (%r), а се очаква "
            "текст — използвам я като текст (\"%s\"); ако е пропусната "
            "кавичка, поправете файла." % (key, value, value))
        return str(value)
    applog.log_warning(
        "config.load_config",
        "стойността на %s в pacho_config.json е от неподходящ тип (%r), а се "
        "очаква текст — пренебрегвам я и използвам подразбиращата се (%r)."
        % (key, value, default))
    return default


def load_config():
    cfg = dict(DEFAULTS)
    # Одит (26.08.2026, находка №1-Б): ЧЕТЕНЕТО също е под катинара — виж
    # обяснението при `_config_lock`. Критичната секция е нарочно СТЕСНЕНА до
    # самото файлово четене: привеждането на типовете по-долу не пипа диска,
    # значи няма причина да държи писачите.
    if os.path.exists(CONFIG_PATH):
        try:
            with _config_lock:
                with open(CONFIG_PATH, "r", encoding="utf-8") as f:
                    loaded = json.load(f)
            # Одит (16.08.2026, находка №45, дребна): валиден JSON, който
            # НЕ е речник (напр. число, низ, гол списък), водеше до
            # TypeError от cfg.update(loaded) по-долу — извън обхванатите
            # (ValueError, OSError), значи гърмеше при самия импорт на
            # модула (config.load_config() се вика при импорт от db.py).
            if isinstance(loaded, dict):
                cfg.update(loaded)
            else:
                raise ValueError("pacho_config.json не съдържа JSON обект (речник)")
        except (ValueError, OSError) as exc:
            # Одит (находка №24): преди тази поправка развален/отрязан
            # файл (напр. токов удар по средата на save_config по-долу)
            # водеше до ТИХО падане към DEFAULTS — db_path="" означава, че
            # програмата тихо създава НОВА празна локална база данни,
            # докато истинската стои недокосната на мрежовия диск/стария
            # път — за потребителя изглежда като пълна загуба на данните,
            # без никакъв признак какво се е случило. Пазим повредения
            # файл настрани (за диагностика/ръчно възстановяване) и
            # логваме предупреждение, вместо мълчаливо да продължим.
            try:
                corrupt_copy = CONFIG_PATH + ".corrupt"
                # Одит (26.08.2026, находка №1-Б): и това четене е под
                # катинара — на Windows всеки отворен handle към CONFIG_PATH
                # блокира os.replace на паралелен запис.
                with _config_lock:
                    with open(CONFIG_PATH, "rb") as src, open(corrupt_copy, "wb") as dst:
                        dst.write(src.read())
            except OSError:
                pass
            applog.log_warning(
                "config.load_config",
                "pacho_config.json е повреден/невалиден (%s) — връщам стойности "
                "по подразбиране (db_path и мрежовите настройки НЕ важат "
                "до ръчна поправка); копие на повредения файл е запазено като "
                "pacho_config.json.corrupt за диагностика." % exc)
    # Одит (19.08.2026, находка №30, средна): привеждането става ТУК, преди
    # първата употреба на стойностите — така всички останали модули четат
    # cfg[...] със сигурността, че текстовите полета са текст.
    for key in _TEXT_KEYS:
        cfg[key] = _coerce_text_setting(key, cfg.get(key), DEFAULTS[key])
    return cfg


def _replace_with_retry(tmp_path, target_path):
    """Одит (26.08.2026, находка №1-Б): `os.replace` с кратък повторен опит
    при „Access is denied“.

    На POSIX `rename()` върху файл, който някой държи отворен, минава винаги
    — тук няма какво да се повтаря и цикълът приключва на първата обиколка.
    На WINDOWS обаче преименуването гърми с `PermissionError [WinError 5]`,
    докато който и да е държи целевия файл отворен. Вътрешнопроцесните четци
    вече са под `_config_lock`, но друг ПРОЦЕС катинарът не достига: втори
    компютър, който чете конфигурацията от същия мрежов дял, антивирусна
    програма или индексаторът на Windows. Всичките държат файла милисекунди.

    След изчерпване на опитите изключението излиза нормално — извикващият го
    логва и старата конфигурация остава непокътната (`os.replace` е атомарен:
    или е минал изцяло, или изобщо не е започнал)."""
    for attempt in range(_REPLACE_RETRIES):
        try:
            os.replace(tmp_path, target_path)
            return
        except PermissionError:
            if attempt == _REPLACE_RETRIES - 1:
                raise
            time.sleep(_REPLACE_RETRY_SLEEP)


def save_config(values):
    # Одит (25.08.2026, находка №1, висока): целият read-modify-write под
    # катинар. Иначе два конкурентни записа могат да прочетат старата
    # конфигурация, всеки да наложи САМО своите промени и да презапише
    # чуждите (lost update) — освен race-а върху временния файл по-долу.
    with _config_lock:
        cfg = load_config()
        cfg.update(values)
        to_write = dict(cfg)
        # Одит (16.08.2026, находка №24): запис през временен файл + os.replace()
        # е атомарен — или старият пълен файл остава непокътнат, или новият,
        # също пълен, го замества; никога отрязано междинно състояние.
        #
        # Одит (25.08.2026, находка №1): временният файл вече е с УНИКАЛНО име
        # (mkstemp), не споделеният CONFIG_PATH + ".tmp". Преди това при
        # застъпване две нишки отваряха един и същ .tmp с "w" (взаимно го
        # отрязваха по средата на json.dump), после os.replace на едната
        # премахваше файла изпод другата → FileNotFoundError. Катинарът
        # по-горе вече сериализира писачите, но уникалното име е втора,
        # независима защита (напр. срещу процес отвън, който пипа .tmp).
        dir_name = os.path.dirname(CONFIG_PATH) or "."
        fd, tmp_path = tempfile.mkstemp(prefix=".pacho_config_", suffix=".tmp",
                                        dir=dir_name)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(to_write, f, ensure_ascii=False, indent=2)
                f.flush()
                os.fsync(f.fileno())
            _replace_with_retry(tmp_path, CONFIG_PATH)
        except OSError:
            # Одит (25.08.2026, находка №1): неуспешният запис вече не се
            # превръща в гол 500 за админа — чистим временния файл и логваме;
            # старата конфигурация остава непокътната (os.replace или е минал
            # изцяло, или изобщо не е стигнал дотам).
            try:
                os.remove(tmp_path)
            except OSError:
                pass
            applog.log_exception(
                "config.save_config: неуспешен запис на pacho_config.json "
                "(старите настройки остават в сила)")
            raise
    return cfg  # актуалната конфигурация — за директна употреба от извикващия код


def get_network_port(cfg, default=5000):
    """Одит (16.08.2026, находка №45, дребна): нечислов `network_port` в
    ръчно редактиран pacho_config.json (традиционният bootstrap за
    мрежови инсталации е точно ръчна редакция на този файл) водеше до
    необработен ValueError от голото `int(...)` на трите места, които го
    четяха (app.py, routes_admin.py) — тиха смърт при старт БЕЗ никакъв
    прозорец/съобщение (в frozen режим само traceback в лога). Толерантен
    parse с ясен fallback вместо срив."""
    raw = cfg.get("network_port")
    try:
        return int(raw) if raw else default
    except (TypeError, ValueError):
        applog.log_warning(
            "config.get_network_port",
            "невалидна стойност network_port=%r в pacho_config.json — "
            "използвам подразбиращия се порт %d" % (raw, default))
        return default


def resolve_db_path(base_dir, default_filename="pacho_logistic.db"):
    cfg = load_config()
    # str(...) е втора защитна мрежа към привеждането в load_config (одит
    # 19.08.2026, находка №30): тази функция се вика при самия ИМПОРТ на
    # db.py — единственото място, където необработено изключение означава
    # програмата изобщо да не се стартира, при това без прозорец.
    custom = str(cfg.get("db_path") or "").strip()
    if custom:
        return custom
    return os.path.join(base_dir, default_filename)
